// The emulator has no SSL and no real credentials; `firebase-admin` detects it from this
// env var. DATACONNECT_EMULATOR_HOST is this repo's name for it (.env.example) — bridged
// here rather than renamed, so every other file can keep the one name.
const emulatorHost = process.env.DATACONNECT_EMULATOR_HOST;
if (emulatorHost && !process.env.DATA_CONNECT_EMULATOR_HOST) {
  process.env.DATA_CONNECT_EMULATOR_HOST = emulatorHost;
}

let dataConnect: DataConnect | undefined;

/** The Firebase SQL Connect Admin client, lazily initialized once per server process. */
export function getConnector(): DataConnect {
  if (!dataConnect) {
    const app = getApps()[0] ?? initializeApp();
    dataConnect = getDataConnect(connectorConfig, app);
  }
  return dataConnect;
}

let pool: Pool | undefined;

function getPool(): Pool {
  if (pool) {
    return pool;
  }
  const connectionString = process.env.DATABASE_URL;
  if (!connectionString) {
    // Never default a production connection string. The emulator is the one environment
    // allowed to fall back, and only because DATACONNECT_EMULATOR_HOST already marks it.
    if (!emulatorHost) {
      throw new Error(
        'DATABASE_URL is required outside the SQL Connect emulator. Refusing to guess a ' +
          'connection string.',
      );
    }
    pool = new Pool({
      connectionString: 'postgres://127.0.0.1:5432/happen_to_have?sslmode=disable',
    });
    return pool;
  }
  pool = new Pool({ connectionString });
  return pool;
}

/**
 * Direct Postgres access for native-SQL queries. Every caller must use parameterized
 * placeholders ($1, $2, ...) — never string-interpolate a value into `sql`.
 */
export const db = {
  query<T extends QueryResultRow = QueryResultRow>(
    sql: string,
    params?: readonly unknown[],
  ): Promise<{ rows: T[] }> {
    return getPool().query<T>(sql, params as unknown[] | undefined);
  },
};
